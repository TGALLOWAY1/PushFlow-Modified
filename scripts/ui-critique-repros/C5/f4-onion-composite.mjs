import { chromium } from 'playwright';
import { readFileSync } from 'fs';
const D = '.ui-repro-out/C5/';
const img = f => 'data:image/png;base64,' + readFileSync(D + f).toString('base64');
const off = img('A-1600x1000-m02-onion-off-full.png');
const on = img('A-1600x1000-m02-onion-on-full.png');
const crop = (src, x, y, w, h) => `<div style="width:${w}px;height:${h}px;background:url(${src}) -${x}px -${y}px no-repeat;border:1px solid #444"></div>`;
const col = (label, src) => `<td style="vertical-align:top;padding:6px"><div style="font-weight:600;margin:4px 0 6px">${label}</div>${crop(src, 12, 100, 318, 120)}<div style="height:8px"></div>${crop(src, 570, 60, 450, 440)}</td>`;
const html = `<html><body style="background:#111;color:#ddd;font:14px sans-serif;margin:10px"><div style="margin:0 6px 6px">Event 02 selected, 1600x1000. Left: onion skin toggle off. Right: toggle on (header icon). The grids are pixel-identical (0 differing pixels).</div><table><tr>${col('Onion skin OFF', off)}${col('Onion skin ON', on)}</tr></table></body></html>`;
const b = await chromium.launch({ executablePath: process.env.PW_CHROMIUM || undefined });
const p = await b.newPage({ viewport: { width: 960, height: 700 } });
await p.setContent(html); await p.waitForTimeout(300);
await p.screenshot({ path: D + 'COMPOSITE-f4-onion-off-vs-on.png', fullPage: true });
await b.close();
